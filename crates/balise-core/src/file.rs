//! Uploaded files: what a `File` field receives, the types Balise recognizes by their
//! content, and where files are stored.
//!
//! A file is written to `<storage.dir>/.uploads` while it arrives (see `multipart`), so it is
//! never held in memory. `File::store` then moves it into `storage.dir`, on the same disk.
//!
//! Without the `runtime` feature, as the macros use this crate, only the declarations and the
//! types are compiled: reading, moving and checking files need the engine.

#![cfg_attr(not(feature = "runtime"), allow(dead_code))]

use std::fmt;
use std::path::{Path, PathBuf};
use std::sync::OnceLock;

/// A `File` field as its `Input` declares it. Generated by `#[derive(Input)]`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct FileSpec {
    /// The field's name in the form.
    pub field: &'static str,
    /// The largest file, in bytes.
    pub max_size: u64,
    /// The accepted types, each one Balise recognizes by content.
    pub types: &'static [&'static str],
    /// How many files the field takes: 1 for `File` and `Option<File>`.
    pub max_count: u32,
}

impl FileSpec {
    /// The most bytes this field can receive.
    pub fn total(&self) -> u64 {
        self.max_size.saturating_mul(u64::from(self.max_count))
    }
}

/// How a type is recognized.
enum Signature {
    /// The content starts with one of these.
    Prefix(&'static [&'static [u8]]),
    /// Another rule on the first bytes.
    Rule(fn(&[u8]) -> bool),
    /// Valid UTF-8 text.
    Text,
}

/// A type Balise can check, with the extension of stored files.
struct FileType {
    mime: &'static str,
    extension: &'static str,
    signature: Signature,
}

/// How many first bytes recognizing a type needs.
pub(crate) const SNIFF_LENGTH: usize = 64;

const ZIP: &[&[u8]] = &[b"PK\x03\x04", b"PK\x05\x06"];

