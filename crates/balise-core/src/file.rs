/// `RIFF`, a size, then the format.
fn riff(head: &[u8], format: &[u8]) -> bool {
    head.len() >= 12 && head.starts_with(b"RIFF") && &head[8..12] == format
}

/// An ISO media file (`ftyp` box) of one of these brands.
fn ftyp(head: &[u8], brands: &[&[u8]]) -> bool {
    head.len() >= 12 && &head[4..8] == b"ftyp" && brands.contains(&&head[8..12])
}

fn find(mime: &str) -> Option<&'static FileType> {
    TYPES.iter().find(|t| t.mime == mime)
}

/// Whether a `File` field can declare this type. Used by the derive.
pub fn is_known(mime: &str) -> bool {
    find(mime).is_some()
}

/// Every type a `File` field can declare, for messages.
pub fn known_types() -> Vec<&'static str> {
    TYPES.iter().map(|t| t.mime).collect()
}

/// Whether a declared type is checked as text.
pub(crate) fn is_text(mime: &str) -> bool {
    find(mime).is_some_and(|t| matches!(t.signature, Signature::Text))
}

/// The declared type, other than text, whose signature the first bytes have.
pub(crate) fn binary_match(declared: &[&'static str], head: &[u8]) -> Option<&'static str> {
    declared.iter().copied().find(|mime| {
        find(mime).is_some_and(|t| match &t.signature {
            Signature::Prefix(prefixes) => prefixes.iter().any(|p| head.starts_with(p)),
            Signature::Rule(rule) => rule(head),
            Signature::Text => false,
        })
    })
}

/// What the first bytes look like, for messages: `image/png`, `text`, `empty`.
pub(crate) fn describe(head: &[u8]) -> String {
    if head.is_empty() {
        return "empty".to_string();
    }
    let all: Vec<&'static str> = TYPES.iter().map(|t| t.mime).collect();
    if let Some(mime) = binary_match(&all, head) {
        return mime.to_string();
    }
    match std::str::from_utf8(head) {
        Ok(_) => "text".to_string(),
        // A character cut at the end of the first bytes is still text.
        Err(error) if error.error_len().is_none() => "text".to_string(),
        Err(_) => "not a recognized type".to_string(),
    }
}

/// `"video/mp4"` or `"video/mp4 or video/webm"`, as messages list the declared types.
pub(crate) fn list(types: &[&str]) -> String {
    match types {
        [] => String::new(),
        [one] => (*one).to_string(),
        [rest @ .., last] => format!("{} or {last}", rest.join(", ")),
    }
}

static STORAGE: OnceLock<PathBuf> = OnceLock::new();

/// Sets `storage.dir`, once at startup.
pub fn set_storage(dir: &str) {
    let _ = STORAGE.set(PathBuf::from(dir));
}

pub(crate) fn storage() -> &'static Path {
    STORAGE.get_or_init(|| PathBuf::from(crate::config::Config::default().storage_dir))
}

/// Where uploads wait while they arrive.
pub(crate) fn uploads() -> PathBuf {
    storage().join(".uploads")
}

/// A file received by a `File` field, already on disk. It is deleted at the end of the
/// request unless it is stored with [`File::store`].
pub struct File {
    path: PathBuf,
    name: String,
    content_type: &'static str,
    size: u64,
    kept: bool,
}

impl File {
    pub(crate) fn uploaded(
        path: PathBuf,
        name: String,
        content_type: &'static str,
        size: u64,
    ) -> File {
        File {
            path,
            name,
            content_type,
            size,
            kept: false,
        }
    }

    #[cfg(test)]
    pub(crate) fn path_for_tests(&self) -> &Path {
        &self.path
    }

    /// The name the client gave it, as information only: it is never used for a path.
    pub fn name(&self) -> &str {
        &self.name
    }

    /// The declared type its content matched, never the type the client claimed.
    pub fn content_type(&self) -> &'static str {
        self.content_type
    }

    /// Its size in bytes.
    pub fn size(&self) -> u64 {
        self.size
    }
}

impl Drop for File {
    fn drop(&mut self) {
        if !self.kept {
            let _ = std::fs::remove_file(&self.path);
        }
    }
}

impl fmt::Debug for File {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("File")
            .field("name", &self.name)
            .field("content_type", &self.content_type)
            .field("size", &self.size)
            .finish()
    }
}

/// A file moved into storage by [`File::store`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StoredFile {
    path: String,
}

impl StoredFile {
    /// Its path within `storage.dir`: `shops/logos/3f9c….png`. Save it to find the file again.
    pub fn path(&self) -> &str {
        &self.path
    }
}

#[cfg(feature = "runtime")]
pub(crate) use io::off_loop;

/// Moving and reading files: with the runtime only, since it does I/O.
#[cfg(feature = "runtime")]
mod io {
    use super::{File, StoredFile, find, storage};
    use crate::error::Error;
    use crate::error_codes::{FILE0005, FILE0006};

    /// Runs file I/O on the blocking pool, so that a slow disk never holds the event loop.
    pub(crate) async fn off_loop<T, F>(work: F) -> std::io::Result<T>
    where
        T: Send + 'static,
        F: FnOnce() -> std::io::Result<T> + Send + 'static,
    {
        match tokio::task::spawn_blocking(work).await {
            Ok(result) => result,
            Err(error) => Err(std::io::Error::other(error.to_string())),
        }
    }

    impl File {
        /// Moves it into `storage.dir/<folder>`, under a name Balise generates:
        /// `input.photo.store("shops/logos").await?`.
        pub async fn store(mut self, folder: &str) -> Result<StoredFile, Error> {
            if !valid_folder(folder) {
                return Err(Error::coded(500, FILE0006, &[("folder", folder)]));
            }
            let extension = find(self.content_type).map_or("bin", |t| t.extension);
            let relative = format!("{folder}/{}.{extension}", crate::text::unique_id());
            let destination = storage().join(&relative);
            let write_error = |cause: std::io::Error| {
                let what = format!("`{}`", destination.display());
                Error::coded(
                    500,
                    FILE0005,
                    &[("what", &what), ("cause", &cause.to_string())],
                )
                .with_cause(cause)
            };
            let (from, folder, to) = (
                self.path.clone(),
                storage().join(folder),
                destination.clone(),
            );
            off_loop(move || {
                std::fs::create_dir_all(folder)?;
                std::fs::rename(from, to)
            })
            .await
            .map_err(write_error)?;
            self.kept = true;
            Ok(StoredFile { path: relative })
        }

        /// Its content, loaded in memory: for files read once, such as an import. Prefer
        /// [`File::store`] for files kept.
        pub async fn read(&self) -> Result<Vec<u8>, Error> {
            let path = self.path.clone();
            off_loop(move || std::fs::read(path))
                .await
                .map_err(|cause| {
                    let what = format!("`{}`", self.path.display());
                    Error::coded(
                        500,
                        FILE0005,
                        &[("what", &what), ("cause", &cause.to_string())],
                    )
                    .with_cause(cause)
                })
        }
    }

    /// `videos`, `shops/logos`: simple names, never a way out of `storage.dir`.
    fn valid_folder(folder: &str) -> bool {
        !folder.is_empty()
            && folder.split('/').all(|name| {
                !name.is_empty()
                    && !name.starts_with('.')
                    && name.chars().all(|c| {
                        c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-' || c == '_'
                    })
            })
    }

    #[cfg(test)]
    mod tests {
        use super::valid_folder;

        #[test]
        fn storage_folders_cannot_leave_the_storage() {
            assert!(valid_folder("videos") && valid_folder("shops/logos"));
            for bad in [
                "", "/videos", "../x", "a/../b", "a//b", ".uploads", "Videos", "a b",
            ] {
                assert!(!valid_folder(bad), "{bad}");
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn types_are_recognized_by_their_first_bytes() {
        let png = b"\x89PNG\r\n\x1a\n\0\0\0\rIHDR";
        assert_eq!(
            binary_match(&["image/jpeg", "image/png"], png),
            Some("image/png")
        );
        assert_eq!(binary_match(&["image/jpeg"], png), None);
        let mp4 = b"\0\0\0\x20ftypisom\0\0\x02\0";
        assert_eq!(binary_match(&["video/mp4"], mp4), Some("video/mp4"));
        let webm = b"\x1a\x45\xdf\xa3\x9f\x42\x86\x81\x01\x42\x82\x84webm";
        assert_eq!(binary_match(&["video/webm"], webm), Some("video/webm"));
        assert_eq!(describe(png), "image/png");
        assert_eq!(describe(b"name,price\n"), "text");
        assert_eq!(describe(b""), "empty");
        assert_eq!(describe(b"\x00\x80\xfe\x01"), "not a recognized type");
    }

    #[test]
    fn every_type_is_known_once() {
        let types = known_types();
        for mime in &types {
            assert_eq!(types.iter().filter(|t| *t == mime).count(), 1, "{mime}");
        }
        assert!(is_known("text/csv") && !is_known("image/svg+xml"));
    }

    #[test]
    fn declared_types_are_listed_for_messages() {
        assert_eq!(list(&["image/png"]), "image/png");
        assert_eq!(list(&["a", "b", "c"]), "a, b or c");
    }
}
